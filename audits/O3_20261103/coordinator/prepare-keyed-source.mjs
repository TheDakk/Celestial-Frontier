/** Root-reserved source preparation only: existing keyer/default D40, no authoring. */
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {intakeAuthoredPixels} from '../../../port/v2/tools/creature-animation/authored-intake.mjs';
import {derivePostKeyMatteFile} from '../../../port/v2/tools/creature-animation/derive-post-key-matte.mjs';
const [out,rawFile,subjectFile,promptFile,keyColor] = process.argv.slice(2);
assert.equal(process.argv.length,7);
assert.ok(['green','magenta'].includes(keyColor));
assert.ok(out.startsWith('audits/O3_20261103/coordinator/') && !out.includes('..'));
assert.ok(!fs.existsSync(out));
const sha=b=>createHash('sha256').update(b).digest('hex');
const pin=p=>({path:p,sha256:sha(fs.readFileSync(p)),bytes:fs.statSync(p).size});
const inputs=[rawFile,subjectFile,promptFile].map(pin);
const write=(p,v)=>fs.writeFileSync(p,JSON.stringify(v,null,2)+'\n',{flag:'wx'});
const req=createRequire(path.join(process.cwd(),'port/v2/package.json'));
const sharp=createRequire(req.resolve('free-tex-packer-core'))('sharp');
const raw=await sharp(rawFile).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const {width:w,height:h}=raw.info;
const keyed=intakeAuthoredPixels(new Uint8ClampedArray(raw.data),w,h,{keyColor});
fs.mkdirSync(out,{recursive:true});
const canonical=out+'/keyed-canonical.png';
fs.writeFileSync(canonical,await sharp(Buffer.from(keyed.rgba),{raw:{width:w,height:h,channels:4}}).png().toBuffer(),{flag:'wx'});
write(out+'/canonical-seal.json',{original:inputs[0],dimensions:[w,h],options:{keyColor},canonical:pin(canonical),rgbaSha256:sha(keyed.rgba),receipt:keyed.receipt,sealRebound:false});
const recipe={schema:'cf.post-key-matte-request/v1',original:inputs[0],canonical:{...pin(canonical),rgbaSha256:sha(keyed.rgba)},lineage:[pin(out+'/canonical-seal.json'),inputs[1],inputs[2]],keyColor,protectedPixels:[],despillPixels:[],scope:'Fresh source painting/edit, first unchanged explicit-key seal and existing default D40. No threshold, seal rebind, resize, source landmarks or owners reused. Material review mandatory.'};
write(out+'/request.json',recipe);
const derivative=await derivePostKeyMatteFile(out+'/request.json',out+'/derivative');
const decoded=await sharp(out+'/derivative/master.png').ensureAlpha().raw().toBuffer({resolveWithObject:true});
assert.equal(decoded.info.width,w);assert.equal(decoded.info.height,h);
assert.equal(sha(intakeAuthoredPixels(new Uint8ClampedArray(decoded.data),w,h).rgba),sha(decoded.data),'Native alpha passes unchanged');
let changed=0;
for(let i=0;i<decoded.data.length;i+=4)if(keyed.rgba[i+3])for(let c=0;c<4;c++)changed+=decoded.data[i+c]!==keyed.rgba[i+c];
assert.equal(changed,0,'Canonical-positive source RGBA unchanged');
const packet=out+'/packet';fs.mkdirSync(packet);
for(const [from,name]of[[out+'/derivative/master.png','master.png'],[subjectFile,'subject-source.json'],[promptFile,'prompt.txt']])fs.copyFileSync(from,packet+'/'+name,fs.constants.COPYFILE_EXCL);
write(packet+'/post-key-lineage.json',{original:inputs[0],canonical:pin(canonical),canonicalRgbaSha256:sha(keyed.rgba),derivative:pin(packet+'/master.png'),receipt:pin(out+'/derivative/post-key-derivative.json'),classification:'Source-bound first default D40 derivative; raw painting edit provenance retained, not untouched prior original',materialApproval:false});
for(const p of inputs)assert.equal(pin(p.path).sha256,p.sha256);
write(out+'/source-preparation.json',{status:'PREPARED_SOURCE_ONLY_MATERIAL_REVIEW_PENDING',dimensions:[w,h],inputs,canonical:pin(canonical),derivative,nativeAlphaPassThrough:true,canonicalPositiveChannelsChanged:changed,sourceLabelsReused:false,sourceLandmarksReused:false,materialApproval:false,authoringExecuted:false,nativeAcceptance:false});
console.log(JSON.stringify({status:'PREPARED_SOURCE_ONLY_MATERIAL_REVIEW_PENDING',out,dimensions:[w,h]}));
