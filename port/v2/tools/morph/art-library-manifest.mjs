// G3 of the Generated Creature Pipeline: the ON-DEMAND art library's manifest. Every regular file under `apps/game/public/library/`
// (the library archetypes' arena files and card files) is listed with its exact byte count and SHA-256, sorted, in
// `public/library/art-library.json` (served beside the files, never listing itself). The manifest's OWN hash and size are then
// written into a generated TypeScript module compiled into the bundle (`art-library.generated.ts`), and the PWA build copies the
// same pin into the service worker: one bundled pin authenticates the manifest, the manifest authenticates every library file, so
// the library can grow to thousands of creatures while the bundle and worker carry a single pin. Deterministic; run by
// build-shipped-battle2.mjs after the card and arena outputs are complete.
import fs from 'node:fs'; import path from 'node:path'; import { createHash } from 'node:crypto';
import { ART_LIBRARY_MANIFEST_FILE, ART_LIBRARY_PUBLIC, ART_LIBRARY_SCHEMA, ART_LIBRARY_SHARD_DIR, ART_LIBRARY_SHARD_INDEX_FILE,
  ART_LIBRARY_SHARD_INDEX_SCHEMA, ART_LIBRARY_SHARD_SCHEMA, artLibraryGroupOf, artLibraryShardFileOf } from './art-library-tiers.mjs';

const R = path.resolve(import.meta.dirname, '../../../..');
export const ART_LIBRARY_ROOT = 'port/v2/apps/game/public/library';
export const ART_LIBRARY_PIN_MODULE = 'port/v2/apps/game/src/art-library.generated.ts';
const sha = (b) => createHash('sha256').update(b).digest('hex');
const byPath = (a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0);

/** The manifest body for a library root (pure given the files on disk). */
export function artLibraryManifestBody(root = path.join(R, ART_LIBRARY_ROOT)) {
  const files = [];
  const walk = (rel) => { for (const e of fs.readdirSync(path.join(root, rel), { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const r = rel ? rel + '/' + e.name : e.name;
    if (e.isSymbolicLink()) throw Error('art library: symlink ' + r);
    if (e.isDirectory()) walk(r);
    else if (e.isFile()) { if (r === ART_LIBRARY_MANIFEST_FILE) continue; if (!/^[A-Za-z0-9_./-]+$/.test(r)) throw Error('art library: unsafe path ' + r);
      const b = fs.readFileSync(path.join(root, r)); files.push({ path: ART_LIBRARY_PUBLIC + r, bytes: b.length, sha256: sha(b) }); }
    else throw Error('art library: not a regular file ' + r); } };
  if (fs.existsSync(root)) walk('');
  files.sort(byPath);
  return { schema: ART_LIBRARY_SCHEMA, files };
}
export const manifestBytes = (body) => Buffer.from(JSON.stringify(body, null, 1) + '\n', 'utf8');
export function pinModuleSource(pin, shardPin) {
  return '// GENERATED by tools/morph/art-library-manifest.mjs (build-shipped-battle2.mjs) — do not edit by hand; re-run the tool.\n'
    + '/** G3: the ONE bundled pin of the on-demand art library manifest (`' + pin.path + '`). The manifest authenticates every library file;\n'
    + ' * the service worker carries the same pin (pwa-build.ts). A manifest whose bytes differ is refused before any library file is used. */\n'
    + `export const ART_LIBRARY_MANIFEST_PIN = Object.freeze({ path: '${pin.path}', sha256: '${pin.sha256}', bytes: ${pin.bytes}, files: ${pin.files} });\n`
    + '/** D56: the pin of the shard index (`' + shardPin.path + '`), which pins one shard per group; the page resolves a file through\n'
    + ' * index → its group\'s shard, so it holds only the groups it used (the whole manifest stays the worker\'s and the build\'s). */\n'
    + `export const ART_LIBRARY_SHARD_INDEX_PIN = Object.freeze({ path: '${shardPin.path}', sha256: '${shardPin.sha256}', bytes: ${shardPin.bytes}, groups: ${shardPin.groups} });\n`;
}
/** True for the generated shard outputs (the index and every shard), which are never content of a shard. */
const isShardOutput = (servedPath) => servedPath === ART_LIBRARY_PUBLIC + ART_LIBRARY_SHARD_INDEX_FILE || servedPath.startsWith(ART_LIBRARY_PUBLIC + ART_LIBRARY_SHARD_DIR);
/** D56: one shard body per group of the CONTENT files (the manifest, index and shards excluded), sorted by group; pure given the files. */
export function artLibraryShardBodies(root = path.join(R, ART_LIBRARY_ROOT)) {
  const groups = new Map();
  for (const f of artLibraryManifestBody(root).files) { if (isShardOutput(f.path)) continue; const g = artLibraryGroupOf(f.path);
    if (!groups.has(g)) groups.set(g, []); groups.get(g).push(f); }
  return [...groups.keys()].sort().map((group) => ({ group, file: artLibraryShardFileOf(group), body: { schema: ART_LIBRARY_SHARD_SCHEMA, group, files: groups.get(group) } }));
}
/** Writes the shards, the shard index, then the manifest (which lists the index and shards, so the worker serves them) and the
 * bundled pins; returns the counts. The shard outputs are regenerated from scratch each run (never edited). */
export function writeArtLibraryManifest(root = path.join(R, ART_LIBRARY_ROOT)) {
  fs.mkdirSync(root, { recursive: true });
  fs.rmSync(path.join(root, ART_LIBRARY_SHARD_DIR), { recursive: true, force: true }); fs.rmSync(path.join(root, ART_LIBRARY_SHARD_INDEX_FILE), { force: true });
  const shards = artLibraryShardBodies(root), index = [];
  fs.mkdirSync(path.join(root, ART_LIBRARY_SHARD_DIR), { recursive: true });
  for (const s of shards) { const b = manifestBytes(s.body); fs.writeFileSync(path.join(root, s.file), b); index.push({ group: s.group, path: ART_LIBRARY_PUBLIC + s.file, bytes: b.length, sha256: sha(b) }); }
  const indexBytes = manifestBytes({ schema: ART_LIBRARY_SHARD_INDEX_SCHEMA, shards: index });
  fs.writeFileSync(path.join(root, ART_LIBRARY_SHARD_INDEX_FILE), indexBytes);
  const body = artLibraryManifestBody(root), bytes = manifestBytes(body);
  fs.writeFileSync(path.join(root, ART_LIBRARY_MANIFEST_FILE), bytes);
  const pin = { path: ART_LIBRARY_PUBLIC + ART_LIBRARY_MANIFEST_FILE, sha256: sha(bytes), bytes: bytes.length, files: body.files.length };
  const shardPin = { path: ART_LIBRARY_PUBLIC + ART_LIBRARY_SHARD_INDEX_FILE, sha256: sha(indexBytes), bytes: indexBytes.length, groups: index.length };
  fs.writeFileSync(path.join(R, ART_LIBRARY_PIN_MODULE), pinModuleSource(pin, shardPin));
  return { files: body.files.length, bytes: body.files.reduce((n, f) => n + f.bytes, 0), pin, shardPin };
}
if (import.meta.url === new URL(process.argv[1], 'file:').href) console.log(JSON.stringify(writeArtLibraryManifest()));
