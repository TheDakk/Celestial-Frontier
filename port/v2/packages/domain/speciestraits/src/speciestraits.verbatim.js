function rarityRoll(seed, salt){
  /* a long-tailed rarity: mostly common, rare spikes, a one-in-a-million summit.
     The deep-spectrum bands (8–11) were carved out of the old unique band, so a
     pre-v1.3 roll either keeps its tier or climbs — determinism never downgrades. */
  const r=mulberry32((hashInt(seed>>>0, salt|0, 0x9a))>>>0)();
  if(r>0.99999997) return 14;  // omnipotent   ~1/33M — the summit
  if(r>0.99999991) return 13;  // eternal      ~1/11M
  if(r>0.9999997)  return 12;  // empyrean     ~1/3.3M
  if(r>0.999999) return 11;    // transcendent — one in a million
  if(r>0.999996) return 10;    // primordial   ~1/333,000
  if(r>0.999985) return 9;     // celestial    ~1/91,000
  if(r>0.99994)  return 8;     // mythic       ~1/22,000
  if(r>0.99976) return 7;      // unique
  if(r>0.992)  return 6;       // anomalous
  if(r>0.972)  return 5;       // legendary
  if(r>0.93)   return 4;       // exotic
  if(r>0.84)   return 3;       // rare
  if(r>0.66)   return 2;       // notable
  if(r>0.40)   return 1;       // uncommon
  return 0;                    // common
}
/* build a color-graded label + tier for any object.
   kindHue: a HUE_FAMILY key. seed: object seed. opts: {boost, force, suffix} */
function colorGrade(kindHue, seed, opts){
  opts=opts||{};
  let tier=rarityRoll(seed, opts.salt||1);
  if(opts.boost) tier=Math.min(TIER_MAX, tier+opts.boost);
  if(opts.force!=null) tier=opts.force;
  const T=GRADE_TIERS[tier];
  const hue=HUE_FAMILY[kindHue]||'Gray';
  /* compose the designation: prefix + (legendary/unique fuse hue with gold/prism) + hue + suffix */
  let label;
  if(tier===7) label='Prismatic '+hue;
  else if(tier===5) label=hue+'-Gold';
  else if(tier===6) label=hue+'-Black';
  else if(T.pre) label=T.pre+' '+hue;
  else label=hue;
  return {tier, name:T.name, label:label+(opts.suffix?' '+opts.suffix:''),
    hex:T.hex, hue, star:T.star, glow: tier>=2};
}
