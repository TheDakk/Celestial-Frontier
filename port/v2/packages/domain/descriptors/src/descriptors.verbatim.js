function describePick(p){
  let d=null, where=null;
  /* v1.7.6 CF173-01 (CRITICAL, fleet round 2): zooming out of a system with a
     survey card open nulls st.star while the panel still renders — every
     st.star.x below threw per-frame. Resolve once; branches that genuinely
     need a live star bail to a null card (renderPanel closes it cleanly). */
  const _S=st.star||null;
  const _sw=_S?{x:_S.x,y:_S.y,seed:_S.seed}:null;
  const _needsStar=['starsys','planet','moon','comet','belt','dwarf','kuiper','oort','visitor'];
  if(!_S && _needsStar.includes(p.kind)) return null;   /* caller treats a null card as 'nothing to show' */
  if(p.kind==='galaxy'){ d=galaxyDescriptor(p.data); where={type:'galaxy', gal:slimGal(p.data)}; }
  else if(p.kind==='quasar'){ d=quasarDescriptor(p.data); where={type:'galaxy', gal:slimGal(p.data)}; }
  else if(p.kind==='star'){ d=starDescriptor(p.data.seed); where={type:'star', gal:slimGal(st.gal), star:{x:p.data.x,y:p.data.y,seed:p.data.seed}}; }
  else if(p.kind==='starsys'){ d=starDescriptor(p.data.seed); where={type:'star', gal:slimGal(st.gal), star:_sw}; }
  else if(p.kind==='planet'){ d=planetDescriptor(p.data.P, p.data.sys, p.data.pl);
    where={type:'planet', gal:slimGal(st.gal), star:_sw, pseed:p.data.P.seed}; }
  else if(p.kind==='moon'){ d=moonDescriptor(p.data.pl, p.data.m);
    where={type:'planet', gal:slimGal(st.gal), star:_sw, pseed:p.data.pl.P.seed}; }
  else if(p.kind==='comet'){ d=cometDescriptor(st.star.seed, p.data.ci, p.data.cm);
    where={type:'star', gal:slimGal(st.gal), star:_sw}; }
  else if(p.kind==='belt'){ d=beltDescriptor(p.data.sys, st.star.seed);
    where={type:'star', gal:slimGal(st.gal), star:_sw}; }
  else if(p.kind==='deco'){ d=decoDescriptor(p.data);
    where={type:'galaxy', gal:slimGal(st.gal)}; }
  else if(p.kind==='worm'){ d=wormholeDescriptor(); where=null; }
  else if(p.kind==='dwarf'){ d=dwarfDescriptor(p.data.dw);
    where={type:'star', gal:slimGal(st.gal), star:_sw}; }
  else if(p.kind==='kuiper'){ d=kuiperDescriptor(p.data.sys, st.star.seed);
    where={type:'star', gal:slimGal(st.gal), star:_sw}; }
  else if(p.kind==='oort'){ d=oortDescriptor(st.star.seed);
    where={type:'star', gal:slimGal(st.gal), star:_sw}; }
  else if(p.kind==='visitor'){ d=visitorDescriptor(st.star.seed);
    where={type:'star', gal:slimGal(st.gal), star:_sw}; }
  else if(p.kind==='radio'){ d=radioDescriptor(p.data);
    where={type:'galaxy', gal:slimGal(p.data)}; }
  else if(p.kind==='snova'){ d=supernovaDescriptor(p.data);
    where={type:'galaxy', gal:slimGal(st.gal)}; }
  else if(p.kind==='protostar'){ d=protostarDescriptor(p.data);
    where={type:'galaxy', gal:slimGal(st.gal)}; }
  else if(p.kind==='cmb'){ d=cmbDescriptor();
    where={type:'galaxy', gal:{x:HOME_POS.x, y:HOME_POS.y, size:78, sp:0, tilt:0.62, rot:0.5, seed:HOME_GAL_SEED, home:true}}; }
  if(d) d.where=where;
  /* custom names: a renamed discovery shows its name everywhere & rides inside share codes */
  if(d && where){
    d._nameKey = where.type==='planet' ? 'p'+where.pseed
               : (where.type==='star' && where.star) ? 's'+where.star.seed
               : (where.gal ? 'g'+where.gal.seed : null);
    if(d._nameKey && customNames.has(d._nameKey)){
      d._origTitle=d.title;
      d.title=customNames.get(d._nameKey);
      d.sub=(d.sub?d.sub+' · ':'')+'named by you';
    }
  }
  return d;
}

