function biosphere(P, sys, band, r){
  if(P.seed===133) return {level:'Abundant — flora and fauna (the home of humanity)', key:'earth'};
  if(sys && sys.sol) return {level:'No known life', key:'none'};   /* the rest of Sol is barren — life begins out among the stars */
  if(P.seed===134) return {level:'Possibly microbial (unconfirmed)', key:'microbial'};
  let level;
  if(P.type==='terran' && band==='temperate') level = r()<0.82?'complex':'flora';
  else if(P.type==='terran' && band==='cold') level = r()<0.55?'sparse':(r()<0.7?'flora':'microbial');
  else if(P.type==='terran' && band==='hot') level = r()<0.4?'sparse':(r()<0.7?'microbial':'none');
  else if(P.type==='ocean' && band==='temperate') level = r()<0.78?'aquatic':'flora';
  else if(P.type==='ocean' && band==='cold') level = r()<0.55?'aquatic':'subsurface';
  /* EXTREMOPHILE FAUNA (v1.3.5, Nick's authorized domain change,
     2026-07-18): a thin slice INSIDE each hostile type's existing draw
     upgrades microbes to actual creatures — sulfur-magma beasts,
     under-ice vent fauna, acid-cloud drifters, deep-vent grazers.
     Same r() consumption as before (nested thresholds on one value),
     so every world OUTSIDE a slice is byte-identical. Chances follow
     real astrobiology: proven-extreme niches ~1-1.5%, speculative
     ~0.1-0.25%, near-impossible 0.04% (a magma-sea beast is a legend). */
  else if(P.type==='ocean' && band==='hot'){ const v=r(); level = v<0.01?'xfauna':(v<0.35?'microbial':'none'); }
  else if(P.type==='desert' && band==='temperate'){ const v=r(); level = v<0.6?'sparse':(v<0.615?'xfauna':'microbial'); }
  else if(P.type==='desert'){ const v=r(); level = v<0.3?'sparse':(v<0.315?'xfauna':'microbial'); }
  else if(P.type==='ice'){ const v=r(); level = v<0.012?'xfauna':(v<0.5?'subsurface':(r()<0.7?'microbial':'none')); }
  else if(P.type==='rocky'){ const v=r(); level = v<0.003?'xfauna':(v<0.18?'microbial':'none'); }
  else if(P.type==='venus'){ const v=r(); level = v<0.001?'xfauna':(v<0.12?'aerial':'none'); }
  else if(P.type==='lava'){ const v=r(); level = v<0.0004?'xfauna':(v<0.1?'microbial':'none'); }
  else if(P.type==='gas'){ const v=r(); level = v<0.0025?'xfauna':(v<0.14?'aerial':'none'); }
  else level='none';
  const LBL={complex:'Abundant — flora and fauna', flora:'Plant-like flora only',
    aquatic:'Aquatic ecosystems', sparse:'Sparse, hardy vegetation', microbial:'Microbial life only',
    subsurface:'Subsurface microbial life (in hidden seas)', aerial:'Airborne microbial life in the cloud layers',
    xfauna:'Extremophile fauna — life that should not be possible here',
    none:'No known life'};
  return {level:LBL[level]||'No known life', key:level};
}

