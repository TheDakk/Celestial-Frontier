function _szOf(g){ return ((+(g&&g.size)||0)%FA_SIZE.length+FA_SIZE.length)%FA_SIZE.length; }
function sapienceTier(g){
  if(!g || g.kingdom!=='fauna') return 0;
  const beh=FA_BEHAVIOR[(g.behavior||0)%FA_BEHAVIOR.length]||'';
  const sense=FA_SENSE[(g.sense||0)%FA_SENSE.length]||'';
  const tr=FA_TRAIT[(g.trait||0)%FA_TRAIT.length]||'';
  let c=0;
  if(/coordinated packs|elaborate nests|infrasound|symbiotic flora/.test(beh)) c+=2;
  else if(/migrating|territorial|seasonal/.test(beh)) c+=1;
  if(/echolocation|magnetic|electroreception/.test(sense)) c+=1;
  if(/harmonic|sing|signal/.test(tr)) c+=1;
  if(_szOf(g)>=3) c+=1;
  const roll=mulberry32(hashInt(g.seed>>>0,0x5A91,3)>>>0)();
  if(c>=4 && roll<0.06) return 4;   /* Sapient — a true mind, vanishingly rare */
  if(c>=3 && roll<0.18) return 3;   /* Semi-sapient — fills the Mind Signature */
  if(c>=2) return 2;                /* Tool-curious */
  if(c>=1) return 1;                /* Social */
  return 0;
}
function realmBiome(g){
  if(g.kingdom==='fauna') return habOf(g);
  if(g.kingdom==='flora') return floraFormOf(g);
  if(g.kingdom==='fungi') return FUNGI_FORM[(g.form||0)%FUNGI_FORM.length]||'';
  return MICROBE_FORM[(g.form||0)%MICROBE_FORM.length]||'';
}
function classifyRealm(g){
  const k=g.kingdom;
  if(k==='flora') return 'Flora';
  if(k==='fungi') return 'Fungi';
  if(k==='microbe'){
    const f=MICROBE_FORM[(g.form||0)%MICROBE_FORM.length]||'';
    return /swarm|colony|bloom|mat|film/.test(f)?'Colonial Life':'Microbial Life';
  }
  /* fauna — read its world from the habitat & locomotion genes */
  const hab=habOf(g);
  const loco=locoOf(g);
  if(sapienceTier(g)>=3) return 'Intelligent Natural Life';
  if(_szOf(g)>=5) return 'Megafauna';
  if(g.x){                        /* extremophiles claim the realms built for them */
    if(/deck/.test(hab)) return 'Gas Giant Life';
    if(/cave/.test(hab)) return 'Subterranean Life';
    return 'Extreme-World Life';
  }
  if((g.heat||1)===2 && /volcanic|ash|vent|lava/.test(hab)) return 'Exotic Biochemistry';
  if(/cavern|subterranean/.test(hab)) return 'Subterranean Life';
  if(/cloud deck/.test(hab)) return 'Gas Giant Life';
  if(/volcanic|tundra|dune|ash|salt-flat/.test(hab)) return 'Extreme-World Life';
  const aquatic=/ocean|reef|shallow|vent|methane lakeshore|ammonia-sea/.test(hab);
  const wetland=/delta|wetland|mangrove/.test(hab);
  const air=/glider|floater|drifter/.test(loco);
  if(wetland) return 'Amphibious Life';
  if(air && !aquatic) return 'Aerial Fauna';
  if(aquatic) return 'Aquatic Fauna';
  return 'Land Fauna';
}
function ecologyRole(g){
  if(g.kingdom==='flora')   return 'Producer — photosynthetic';
  if(g.kingdom==='microbe') return 'Producer — base of the food web';
  if(g.kingdom==='fungi')   return 'Decomposer — recycles matter';
  const diet=FA_DIET[(g.diet||0)%FA_DIET.length]||'';
  if(/herbivore/.test(diet)) return 'Grazer / herbivore';
  if(/carnivore/.test(diet)) return 'Predator';
  if(/filter/.test(diet))    return 'Filter feeder';
  if(/scaveng/.test(diet))   return 'Scavenger';
  if(/chemo/.test(diet))     return 'Chemosynthetic grazer';
  return 'Omnivore';
}
