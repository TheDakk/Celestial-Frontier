function describeSpecies(g){
  const col=SP_COLOR[g.color%SP_COLOR.length];
  if(g.kingdom==='flora'){
    const detail=FLORA_DETAIL[(g.detail||0)%FLORA_DETAIL.length];
    return {name:speciesName(g.seed), kind:'Flora', grade:speciesGrade(g),
      desc:col+' '+floraFormOf(g)+(g.lumin?', faintly bioluminescent':''),
      detail:'A photosynthetic species, '+detail+'.'};
  }
  if(g.kingdom==='fungi'){
    return {name:speciesName(g.seed), kind:'Fungi', grade:speciesGrade(g),
      desc:col+' '+FUNGI_FORM[g.form%FUNGI_FORM.length]+(g.lumin?', glowing softly':''),
      detail:'A fungal organism breaking down matter and feeding the wider web of life.'};
  }
  if(g.kingdom==='microbe'){
    return {name:speciesName(g.seed), kind:'Microbe', grade:speciesGrade(g),
      desc:col+' '+MICROBE_FORM[g.form%MICROBE_FORM.length],
      detail:'Microscopic life — the hardy foundation every larger ecosystem is built upon.'};
  }
  // fauna — assembled from anatomy genes
  return faunaDesc(g);
}
function speciesGrade(g){
  /* a creature's rarity rises with size, luminescence, evolution depth and hybrid generation —
     plus the long-tail roll, so a titanic glowing gen-5 hybrid can climb past Unique
     into the deep spectrum (Mythic → Transcendent). */
  const dom = g.kingdom==='fauna'?'life':(g.kingdom==='flora'?'forest':(g.kingdom==='fungi'?'fungal':'life'));
  /* apex guardians wear their summit grade outright — forced, never rolled */
  if(g.apex) return colorGrade(dom, g.seed, {salt:0x10F, force:Math.min(TIER_MAX, Math.max(12, g.apex|0))});
  /* the Fifty Paragons wear forced deep-spectrum grades (8–11) the same way */
  if(g.par) return colorGrade(dom, g.seed, {salt:0x10F, force:Math.min(11, Math.max(8, g.par|0))});
  let boost=0;
  if(_szOf(g)>=4) boost++;
  if(_szOf(g)>=5) boost++;
  if(g.lumin) boost++;
  if((g.gen||0)>=2) boost++;
  if((g.gen||0)>=5) boost++;
  if(g.wild) boost++;
  return colorGrade(dom, g.seed, {salt:0x10F, boost});
}
