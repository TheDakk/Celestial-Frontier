  for(const k of ['color','form','body','loco','trait','size','diet','head','limbs','skin','tail',
                  'pattern','eyes','behavior','habitat','detail','accent','temper','sense','repro',
                  'life','metab','gen','heat'])
    o[k]=Number.isFinite(+o[k])?Math.abs((+o[k])|0):0;
  o.brood=Math.min(200, Number.isFinite(+o.brood)?Math.abs((+o.brood)|0):0);
  o.fed=Math.min(200, Number.isFinite(+o.fed)?Math.abs((+o.fed)|0):0);
  o.lumin=!!o.lumin;
  /* guardian/paragon fields: ep is a display index; apex/par only honor genuine bands */
  if(o.ep!=null) o.ep=Number.isFinite(+o.ep)?Math.abs((+o.ep)|0):0;
  if(o.apex!=null){ const a=(+o.apex)|0; if(a>=12 && a<=TIER_MAX) o.apex=a; else delete o.apex; }
  if(o.par!=null){ const a=(+o.par)|0; if(a>=8 && a<=11) o.par=a; else delete o.par; }
  delete o.parents;
  delete o.hurt;          /* imported challengers arrive fresh — injuries don't travel in codes */
  delete o.xp;            /* levels are YOUR creature's story — a shared one starts at 1 */
