function decodeCreature(code){
  try{
    if(String(code||'').length>8192) return null;   /* CF-CR-010: same bound as CF1 */
    const h=String(code).indexOf('CFB-'); if(h<0) return null;
    let b64=String(code).slice(h+4).trim().replace(/-/g,'+').replace(/_/g,'/');
    while(b64.length%4) b64+='=';
    const o=JSON.parse(b64decUtf8(b64));
    if(!o || !o.g || o.g.seed==null) return null;
    const gen=normGenome(o.g);   /* strips xp for anti-cheat */
    const out={genome:gen, name:(o.n?cleanName(o.n):'')||'Challenger'};
    /* v1.6 CHAMPION CODE: an exhibit code re-applies the shared level (clamped
       to the level-9 ceiling) so the champion shows at full strength — but it
       is EXHIBIT-ONLY: a challenger to duel, never an owned/breedable creature */
    if(o.x!=null){ gen.xp=clamp((+o.x)|0, 0, 6*81); out.exhibit=true; }
    return out;
  }catch(_){ return null; }
}
function runDuel(mine, theirs){
  const A=mine.stats||battleStats(mine.genome), B=theirs.stats||battleStats(theirs.genome);
  const r=mulberry32(hashInt(mine.genome.seed>>>0, theirs.genome.seed>>>0, 0xD0E1)>>>0);
  const maxA=A.vit*3, maxB=B.vit*3;
  /* CF-CR-007 (review, measured): `>=` handed side A EVERY agility tie — 93.5%
     first-slot win rate across 5,000 exact mirrors. Ties now break by a seeded
     coin keyed to the matchup: deterministic and replayable per pairing, fair
     across pairings. The coin CASCADES the hash (first seed fully avalanched
     before the second enters) because hashInt's opening `h^x` collapses to a
     constant for identical or xor-related seeds — the exact mirror case. */
  let hpA=maxA, hpB=maxB,
      turnA=A.agi>B.agi || (A.agi===B.agi &&
        ((hashInt(hashInt(mine.genome.seed>>>0, 0x9E37, 0x71EB), theirs.genome.seed>>>0, 0x85EB)>>>8)&1)===0);
  const _turnA0=turnA;   /* CF1715-20: the log renders initiative from the RESOLVED first mover */
  let rampA=0, rampB=0, firstA=true, firstB=true;
  let shredA=0, shredB=0, skipA=false, skipB=false;   /* shredX = bonus damage X SUFFERS; skipX = X's next strike staggered away */
  const log=[];
  const strike=()=>{
    const att=turnA?A:B, def=turnA?B:A;
    const an=turnA?mine.name:theirs.name, dn=turnA?theirs.name:mine.name;
    /* shock: a staggered fighter loses this strike */
    if(turnA?skipA:skipB){
      if(turnA) skipA=false; else skipB=false;
      log.push({an, dn, stun:true, hpA, hpB});
      return;
    }
    /* camouflage: defender slips away */
    if(def.ab.dodge && r()<def.ab.dodge){
      log.push({an, dn, dodge:true, hpA, hpB});
      return;
    }
    const crit=r()<Math.min(0.95, att.ins/420 + (att.ab.critB||0));   /* CF1715-26: max Instinct + Eye V reached 112.8% — every point past 95% was dead */
    const ramp=turnA?rampA:rampB;
    let fs=false, ex=false, tb=0, ls=0, stp=false;   /* the chronicle remembers everything */
    let dmg=att.fer*(1+ramp)*(0.8+r()*0.5) - def.res*0.45;
    if(att.ab.dmg) dmg*=att.ab.dmg;
    if(def.ab.taken) dmg*=def.ab.taken;
    if(att.ab.first && (turnA?firstA:firstB)){ dmg*=att.ab.first; fs=true; }
    /* the matrix verbs (1.0) — every branch guarded, so legacy ability sets
       consume the identical rng sequence and compute byte-identically */
    if(att.ab.enrage){ const _mf=turnA?(1-hpA/maxA):(1-hpB/maxB); dmg*=1+att.ab.enrage*_mf; }   /* rage: blood for power */
    if(att.ab.gambit) dmg*=(1-att.ab.gambit*0.45)+r()*att.ab.gambit*1.45;   /* roulette: wild swings */
    dmg*=1+(turnA?shredB:shredA);                                            /* rend: torn defenses */
    if(att.ab.execB && (turnA?(hpB<maxB*0.5):(hpA<maxA*0.5))){ dmg*=1+att.ab.execB; ex=true; }  /* reckoning */
    dmg=Math.max(2, Math.round(att.fer*0.10), Math.round(dmg));   /* CF1715-06: a flat floor of 2 made full-defence builds 0-for-4,000 (13 strikes x 2 = 26 dmg vs vit*3 pools) and the flora kingdom mechanically unable to win — mitigation now caps near 90% */
    if(crit) dmg=Math.round(dmg*1.7);
    if(def.ab.cap) dmg=Math.min(dmg, Math.max(3, Math.round((turnA?maxB:maxA)*def.ab.cap)));  /* bulwark */
    if(turnA){ hpB=Math.max(0,hpB-dmg); firstA=false; }
    else { hpA=Math.max(0,hpA-dmg); firstB=false; }
    if(att.ab.shred){ if(turnA) shredB+=att.ab.shred; else shredA+=att.ab.shred; }
    if(def.ab.thorns){ tb=Math.max(1,Math.round(dmg*def.ab.thorns));         /* thorns bite back */
      if(turnA) hpA=Math.max(0,hpA-tb); else hpB=Math.max(0,hpB-tb); }
    if(att.ab.stun && r()<att.ab.stun){ if(turnA) skipB=true; else skipA=true; stp=true; }
    if(crit && att.ab.drink){
      ls=Math.round(dmg*0.3);
      if(turnA) hpA=Math.min(maxA,hpA+ls); else hpB=Math.min(maxB,hpB+ls);
    }
    log.push({an, dn, dmg, crit, fs, ex, tb, ls, stp, side:turnA?'A':'B', hpA, hpB});
  };
  for(let round=0; round<26 && hpA>0 && hpB>0; round++){
    strike();
    /* swift hunter: a second strike */
    const att=turnA?A:B;
    if(hpA>0 && hpB>0 && att.ab.dbl && r()<att.ab.dbl) strike();
    /* regenerators knit themselves back together; afflictions burn — and the
       chronicle keeps the receipts (tick entries for the battle log) */
    let _rA=0,_rB=0,_bA=0,_bB=0;
    if(hpA>0 && A.ab.regen){ _rA=Math.round(maxA*A.ab.regen*0.5); hpA=Math.min(maxA, hpA+_rA); }
    if(hpB>0 && B.ab.regen){ _rB=Math.round(maxB*B.ab.regen*0.5); hpB=Math.min(maxB, hpB+_rB); }
    /* pack howl: fury builds */
    if(A.ab.ramp) rampA+=A.ab.ramp*0.5;   /* CF1715-03: the loop ticks per HALF-turn (26x vs 13 strikes) — regen carried a *0.5 for exactly this; ramp and burn never did */
    if(B.ab.ramp) rampB+=B.ab.ramp*0.5;
    if(A.ab.burn && hpB>0){ _bB=Math.max(1,Math.round(maxB*A.ab.burn*0.5)); hpB=Math.max(0, hpB-_bB); }   /* CF1715-03: unhalved, Cinderburn dealt 130% of max HP per duel THROUGH defence — 98.3% vs identical no-ability */
    if(B.ab.burn && hpA>0){ _bA=Math.max(1,Math.round(maxA*B.ab.burn*0.5)); hpA=Math.max(0, hpA-_bA); }
    if(_rA||_rB||_bA||_bB) log.push({tick:true, rA:_rA, rB:_rB, bA:_bA, bB:_bB, hpA, hpB});
    turnA=!turnA;
  }
  const _fa=hpA/maxA, _fb=hpB/maxB;
  /* CF1715-04: >= handed the player EVERY exact-fraction tie at the round cap (79.9% of tank mirrors) — the same operator class the initiative fix killed; ties break on the cascaded seeded coin */
  const winner = (hpA<=0&&hpB<=0)?null : hpA<=0?'B' : hpB<=0?'A'
    : _fa>_fb?'A' : _fa<_fb?'B'
    : (((hashInt(hashInt(mine.genome.seed>>>0,0x9E37,0x71EB), theirs.genome.seed>>>0,0x85EB)>>>9)&1)===0?'A':'B');   /* CF1718-02: A/B are STAT BLOCKS — reading A.genome compiled the coin to a constant 'A'; the combatants' seeds are the ones in scope, exactly as the initiative coin uses */
  return {A, B, log, winner, hpA, hpB, maxA, maxB, turnA0:_turnA0};   /* CF1715-20: the log renders initiative from the RESOLVED coin, not a >= re-guess (contradicted the fight 49.4% of equal-AGI duels) */
}

