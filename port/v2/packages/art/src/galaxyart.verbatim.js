    /* lenticular: a smooth, armless disk of older stars */
    let dg=g.createRadialGradient(0,0,0,0,0,G_PX*0.46);
    dg.addColorStop(0,'#fff2da');
    dg.addColorStop(0.15,'hsla(38,55%,78%,0.9)');
